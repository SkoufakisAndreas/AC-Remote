//INPUT PIN 9 INTERRUPT CALLBACK FUNCTION
//This function mesures the pulse width of the received IR signal
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin){

  HAL_TIM_Base_Start_IT(&htim11);  //enable timer interrupts

  if(GPIO_Pin == GPIO_PIN_9){ //If intrp was casued by our IR input signal

     if(read_flag == 0){
       read_flag = 1; //Set the flag one for the next read 
       __HAL_TIM_SET_COUNTER(&htim11, 0); //Reset the timer counter to 0
       pulse_index = 0;
     }

     else if(read_flag == 1){
        pulse_width[pulse_index] = __HAL_TIM_GET_COUNTER(&htim11); //Get the timer cntr value
        __HAL_TIM_SET_COUNTER(&htim11, 0); //Reset the timer counter to 0

        if(pulse_index < 799) pulse_index++; //Only increment if we are within limits
        
     }
  } 
}

